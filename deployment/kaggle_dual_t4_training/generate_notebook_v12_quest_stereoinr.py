            "class DynamicTanh(nn.Module):\n",
            "    def __init__(self, channels: int):\n",
            "        super().__init__()\n",
            "        self.alpha = nn.Parameter(torch.ones(1, channels, 1, 1))\n",
            "        self.gamma = nn.Parameter(torch.ones(1, channels, 1, 1))\n",
            "        self.beta = nn.Parameter(torch.zeros(1, channels, 1, 1))\n",
            "    def forward(self, x: torch.Tensor) -> torch.Tensor:\n",
            "        return self.gamma * torch.tanh(self.alpha * x) + self.beta\n",
            "\n",
            "class RepDyTNAFBlock(nn.Module):\n",
            "    def __init__(self, channels: int):\n",
            "        super().__init__()\n",
            "        self.channels = channels\n",
            "        self.is_deploy = False\n",
            "        self.conv1_3x3 = nn.Conv2d(channels, channels, 3, padding=1, groups=channels, bias=True)\n",
            "        self.conv1_1x1 = nn.Conv2d(channels, channels, 1, padding=0, groups=channels, bias=True)\n",
            "        self.identity = nn.Identity()\n",
            "        self.dyt = DynamicTanh(channels)\n",
            "        self.pw_expand = nn.Conv2d(channels, channels * 2, 1, bias=True)\n",
            "        self.pw_squeeze = nn.Conv2d(channels, channels, 1, bias=True)\n",
            "        self.fused_conv = None\n",
            "\n",
            "    def forward(self, x: torch.Tensor) -> torch.Tensor:\n",
            "        if self.is_deploy:\n",
            "            out = self.fused_conv(x)\n",
            "        else:\n",
            "            out = self.conv1_3x3(x) + self.conv1_1x1(x) + self.identity(x)\n",
            "        out = self.dyt(out)\n",
            "        x1, x2 = self.pw_expand(out).chunk(2, dim=1)\n",
            "        out = self.pw_squeeze(x1 * torch.sigmoid(x2))\n",
            "        return x + out\n",
            "\n",
            "    def switch_to_deploy(self):\n",
            "        if self.is_deploy:\n",
            "            return\n",
            "        w_3x3 = self.conv1_3x3.weight.data\n",
            "        b_3x3 = self.conv1_3x3.bias.data\n",
            "        w_1x1 = F.pad(self.conv1_1x1.weight.data, (1, 1, 1, 1))\n",
            "        b_1x1 = self.conv1_1x1.bias.data\n",
            "        w_id = torch.zeros_like(w_3x3)\n",
            "        for i in range(self.channels):\n",
            "            w_id[i, 0, 1, 1] = 1.0\n",
            "        b_id = torch.zeros_like(b_3x3)\n",
            "        fused_w = w_3x3 + w_1x1 + w_id\n",
            "        fused_b = b_3x3 + b_1x1 + b_id\n",
            "        self.fused_conv = nn.Conv2d(self.channels, self.channels, 3, padding=1, groups=self.channels, bias=True)\n",
            "        self.fused_conv.weight.data.copy_(fused_w)\n",
            "        self.fused_conv.bias.data.copy_(fused_b)\n",
            "        self.is_deploy = True\n",
            "        del self.conv1_3x3, self.conv1_1x1, self.identity\n",
            "\n",
            "class OcclusionGatedWindowedSCAM(nn.Module):\n",
            "    def __init__(self, channels: int, min_disp: int = -2, max_disp: int = 14, sigma_occ: float = 1.0):\n",
            "        super().__init__()\n",
            "        self.channels = channels\n",
            "        self.min_disp = min_disp\n",
            "        self.max_disp = max_disp\n",
            "        self.sigma_occ = sigma_occ\n",
            "        self.scale = channels ** -0.5\n",
            "        self.q_l = nn.Conv2d(channels, channels, 1, bias=False)\n",
            "        self.k_r = nn.Conv2d(channels, channels, 1, bias=False)\n",
            "        self.v_r = nn.Conv2d(channels, channels, 1, bias=False)\n",
            "        self.q_r = nn.Conv2d(channels, channels, 1, bias=False)\n",
            "        self.k_l = nn.Conv2d(channels, channels, 1, bias=False)\n",
            "        self.v_l = nn.Conv2d(channels, channels, 1, bias=False)\n",
            "        for conv in [self.q_l, self.k_r, self.v_r, self.q_r, self.k_l, self.v_l]:\n",
            "            nn.init.dirac_(conv.weight)\n",
            "        self.beta = nn.Parameter(torch.zeros(1, channels, 1, 1))\n",
            "        self.gamma = nn.Parameter(torch.zeros(1, channels, 1, 1))\n",
            "\n",
            "    def forward(self, x_l: torch.Tensor, x_r: torch.Tensor, return_disp: bool = False, return_mask: bool = False):\n",
            "        B, C, H, W = x_l.shape\n",
            "        ql, kr, vr = self.q_l(x_l), self.k_r(x_r), self.v_r(x_r)\n",
            "        qr, kl, vl = self.q_r(x_r), self.k_l(x_l), self.v_l(x_l)\n",
            "        corr_l2r, corr_r2l = [], []\n",
            "        shifted_vr, shifted_vl = [], []\n",
            "        for offset in range(self.min_disp, self.max_disp + 1):\n",
            "            if offset > 0:\n",
            "                kr_s = F.pad(kr[:, :, :, :-offset], (offset, 0, 0, 0), mode='replicate')\n",
            "                vr_s = F.pad(vr[:, :, :, :-offset], (offset, 0, 0, 0), mode='replicate')\n",
            "                kl_s = F.pad(kl[:, :, :, offset:], (0, offset, 0, 0), mode='replicate')\n",
            "                vl_s = F.pad(vl[:, :, :, offset:], (0, offset, 0, 0), mode='replicate')\n",
            "            elif offset < 0:\n",
            "                abs_o = abs(offset)\n",
            "                kr_s = F.pad(kr[:, :, :, abs_o:], (0, abs_o, 0, 0), mode='replicate')\n",
            "                vr_s = F.pad(vr[:, :, :, abs_o:], (0, abs_o, 0, 0), mode='replicate')\n",
            "                kl_s = F.pad(kl[:, :, :, :-abs_o], (abs_o, 0, 0, 0), mode='replicate')\n",
            "                vl_s = F.pad(vl[:, :, :, :-abs_o], (abs_o, 0, 0, 0), mode='replicate')\n",
            "            else:\n",
            "                kr_s, vr_s, kl_s, vl_s = kr, vr, kl, vl\n",
            "            corr_l2r.append(torch.sum(ql * kr_s, dim=1, keepdim=True) * self.scale)\n",
            "            corr_r2l.append(torch.sum(qr * kl_s, dim=1, keepdim=True) * self.scale)\n",
            "            shifted_vr.append(vr_s)\n",
            "            shifted_vl.append(vl_s)\n",
            "\n",
            "        weights_l2r = F.softmax(torch.cat(corr_l2r, dim=1), dim=1)\n",
            "        weights_r2l = F.softmax(torch.cat(corr_r2l, dim=1), dim=1)\n",
            "        f_r2l = sum(weights_l2r[:, i:i+1] * shifted_vr[i] for i in range(len(shifted_vr)))\n",
            "        f_l2r = sum(weights_r2l[:, i:i+1] * shifted_vl[i] for i in range(len(shifted_vl)))\n",
            "\n",
            "        disp_vals = torch.arange(self.min_disp, self.max_disp + 1, device=x_l.device, dtype=x_l.dtype).view(1, -1, 1, 1)\n",
            "        disp_l2r = torch.sum(weights_l2r * disp_vals, dim=1, keepdim=True)\n",
            "        disp_r2l_mag = torch.sum(weights_r2l * disp_vals, dim=1, keepdim=True)\n",
            "\n",
            "        grid_y = (torch.arange(H, device=x_l.device, dtype=x_l.dtype).view(1, H, 1) / max(float(H) - 1.0, 1e-5) * 2.0 - 1.0).expand(B, H, W)\n",
            "        grid_x = (torch.arange(W, device=x_l.device, dtype=x_l.dtype).view(1, 1, W) / max(float(W) - 1.0, 1e-5) * 2.0 - 1.0).expand(B, H, W)\n",
            "        norm_disp_l = (disp_l2r.squeeze(1) * 2.0) / float(W)\n",
            "        flow_l2r = torch.stack((grid_x - norm_disp_l, grid_y), dim=-1)\n",
            "        warped_disp_r = F.grid_sample(disp_r2l_mag, flow_l2r, mode='bilinear', padding_mode='border', align_corners=True)\n",
            "        lrc_error_l = torch.abs(disp_l2r - warped_disp_r)\n",
            "\n",
            "        norm_disp_r = (disp_r2l_mag.squeeze(1) * 2.0) / float(W)\n",
            "        flow_r2l = torch.stack((grid_x + norm_disp_r, grid_y), dim=-1)\n",
            "        warped_disp_l = F.grid_sample(disp_l2r, flow_r2l, mode='bilinear', padding_mode='border', align_corners=True)\n",
            "        lrc_error_r = torch.abs(disp_r2l_mag - warped_disp_l)\n",
            "\n",
            "        k_disp = self.max_disp - self.min_disp + 1\n",
            "        uniform_b = 1.0 / k_disp\n",
            "        max_w_l = weights_l2r.max(dim=1, keepdim=True)[0]\n",
            "        max_w_r = weights_r2l.max(dim=1, keepdim=True)[0]\n",
            "        p_sharp_l = torch.clamp((max_w_l - uniform_b) / (1.0 - uniform_b), 0.0, 1.0) ** 2\n",
            "        p_sharp_r = torch.clamp((max_w_r - uniform_b) / (1.0 - uniform_b), 0.0, 1.0) ** 2\n",
            "        m_occ_l = torch.exp(-(lrc_error_l ** 2) / (2.0 * self.sigma_occ ** 2)) * p_sharp_l\n",
            "        m_occ_r = torch.exp(-(lrc_error_r ** 2) / (2.0 * self.sigma_occ ** 2)) * p_sharp_r\n",
            "\n",
            "        out_l = x_l + (f_r2l * m_occ_l) * self.beta\n",
            "        out_r = x_r + (f_l2r * m_occ_r) * self.gamma\n",
            "        if return_disp and return_mask:\n",
            "            return out_l, out_r, disp_l2r, m_occ_l, m_occ_r\n",
            "        if return_disp: return out_l, out_r, disp_l2r\n",
            "        if return_mask: return out_l, out_r, m_occ_l, m_occ_r\n",
            "        return out_l, out_r\n",
            "\n",
            "class ContinuousCoordinateEncoder(nn.Module):\n",
            "    def __init__(self, in_dim: int = 3, out_dim: int = 32):\n",
            "        super().__init__()\n",
            "        self.mlp = nn.Sequential(\n",
            "            nn.Linear(in_dim, out_dim),\n",
            "            nn.GELU(),\n",
            "            nn.Linear(out_dim, out_dim)\n",
            "        )\n",
            "    def forward(self, rel_coords: torch.Tensor, scale: float) -> torch.Tensor:\n",
            "        B, H, W, _ = rel_coords.shape\n",
            "        scale_tensor = torch.full((B, H, W, 1), float(scale), device=rel_coords.device, dtype=rel_coords.dtype)\n",
            "        inputs = torch.cat((rel_coords, scale_tensor), dim=-1)\n",
            "        encoded = self.mlp(inputs)\n",
            "        return encoded.permute(0, 3, 1, 2)\n",
            "\n",
            "class QuestStereoINR(nn.Module):\n",
            "    def __init__(self, in_channels: int = 3, width: int = 48, num_blocks: int = 4, coord_dim: int = 32):\n",
            "        super().__init__()\n",
            "        self.width = width\n",
            "        self.intro = nn.Conv2d(in_channels, width, 3, padding=1, bias=True)\n",
            "        self.stereo_fusion = OcclusionGatedWindowedSCAM(channels=width)\n",
            "        self.blocks = nn.ModuleList([RepDyTNAFBlock(width) for _ in range(num_blocks)])\n",
            "        self.coord_encoder = ContinuousCoordinateEncoder(in_dim=3, out_dim=coord_dim)\n",
            "        self.decode_head = nn.Sequential(\n",
            "            nn.Conv2d(width + coord_dim, width, 3, padding=1, bias=True),\n",
            "            DynamicTanh(width),\n",
            "            nn.Conv2d(width, in_channels, 3, padding=1, bias=True)\n",
            "        )\n",
            "        self.fast_up_4x = nn.Sequential(\n",
            "            nn.Conv2d(width, in_channels * 16, 3, padding=1, bias=True),\n",
            "            nn.PixelShuffle(4)\n",
            "        )\n",
            "        self.ifd_proj = nn.Conv2d(width, 64, kernel_size=1, bias=True)\n",
            "        # ZERO-INIT MONOTONIC GUARANTEE (Both output heads initialized to exact zero)\n",
            "        nn.init.zeros_(self.decode_head[-1].weight)\n",
            "        nn.init.zeros_(self.decode_head[-1].bias)\n",
            "        nn.init.zeros_(self.fast_up_4x[0].weight)\n",
            "        nn.init.zeros_(self.fast_up_4x[0].bias)\n",
            "\n",
            "    def switch_to_deploy(self):\n",
            "        for b in self.blocks: b.switch_to_deploy()\n",
            "\n",
            "    def extract_deep_features(self, img_l: torch.Tensor, img_r: torch.Tensor):\n",
            "        fl = self.intro(img_l)\n",
            "        fr = self.intro(img_r)\n",
            "        for blk in self.blocks:\n",
            "            fl, fr = self.stereo_fusion(fl, fr)\n",
            "            fl = blk(fl)\n",
            "            fr = blk(fr)\n",
            "        fl, fr = self.stereo_fusion(fl, fr)\n",
            "        return fl, fr\n",
            "\n",
            "    def query_continuous_coordinates(self, feat: torch.Tensor, scale: float, target_h: int, target_w: int):\n",
            "        B, C, H, W = feat.shape\n",
            "        grid_y, grid_x = torch.meshgrid(\n",
            "            torch.linspace(-1, 1, target_h, device=feat.device),\n",
            "            torch.linspace(-1, 1, target_w, device=feat.device),\n",
            "            indexing='ij'\n",
