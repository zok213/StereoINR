            "class DynamicTanh(nn.Module):\n",
            "    def __init__(self, channels: int):\n",
            "        super().__init__()\n",
            "        self.alpha = nn.Parameter(torch.ones(1, channels, 1, 1))\n",
            "        self.gamma = nn.Parameter(torch.ones(1, channels, 1, 1))\n",
            "        self.beta = nn.Parameter(torch.zeros(1, channels, 1, 1))\n",
            "    def forward(self, x: torch.Tensor) -> torch.Tensor:\n",
            "        return self.gamma * torch.tanh(self.alpha * x) + self.beta\n",
            "\n",
            "class SimpleGate(nn.Module):\n",
            "    def forward(self, x: torch.Tensor) -> torch.Tensor:\n",
            "        x1, x2 = x.chunk(2, dim=1)\n",
            "        return x1 * x2\n",
            "\n",
            "class WindowedSCAM(nn.Module):\n",
            "    def __init__(self, c: int, min_disp: int = -2, max_disp: int = 14, init_coupling: float = 0.15):\n",
            "        super().__init__()\n",
            "        self.min_disp = min_disp\n",
            "        self.max_disp = max_disp\n",
            "        self.scale = c ** -0.5\n",
            "        self.q_l = nn.Conv2d(c, c, kernel_size=1, bias=False)\n",
            "        self.k_r = nn.Conv2d(c, c, kernel_size=1, bias=False)\n",
            "        self.v_r = nn.Conv2d(c, c, kernel_size=1, bias=False)\n",
            "        self.q_r = nn.Conv2d(c, c, kernel_size=1, bias=False)\n",
            "        self.k_l = nn.Conv2d(c, c, kernel_size=1, bias=False)\n",
            "        self.v_l = nn.Conv2d(c, c, kernel_size=1, bias=False)\n",
            "        self.beta = nn.Parameter(torch.full((1, c, 1, 1), init_coupling))\n",
            "        self.gamma = nn.Parameter(torch.full((1, c, 1, 1), init_coupling))\n",
            "    def forward(self, x_l: torch.Tensor, x_r: torch.Tensor, return_disp: bool = False):\n",
            "        ql = self.q_l(x_l)\n",
            "        kr = self.k_r(x_r)\n",
            "        vr = self.v_r(x_r)\n",
            "        qr = self.q_r(x_r)\n",
            "        kl = self.k_l(x_l)\n",
            "        vl = self.v_l(x_l)\n",
            "        corr_l2r, corr_r2l, shifted_v_r, shifted_v_l = [], [], [], []\n",
            "        for d in range(self.min_disp, self.max_disp + 1):\n",
            "            if d >= 0:\n",
            "                kr_s = F.pad(kr[:, :, :, d:], (0, d, 0, 0))\n",
            "                vr_s = F.pad(vr[:, :, :, d:], (0, d, 0, 0))\n",
            "            else:\n",
            "                kr_s = F.pad(kr[:, :, :, :d], (-d, 0, 0, 0))\n",
            "                vr_s = F.pad(vr[:, :, :, :d], (-d, 0, 0, 0))\n",
            "            corr_l2r.append(torch.sum(ql * kr_s, dim=1, keepdim=True) * self.scale)\n",
            "            shifted_v_r.append(vr_s)\n",
            "            d_rev = -d\n",
            "            if d_rev >= 0:\n",
            "                kl_s = F.pad(kl[:, :, :, d_rev:], (0, d_rev, 0, 0))\n",
            "                vl_s = F.pad(vl[:, :, :, d_rev:], (0, d_rev, 0, 0))\n",
            "            else:\n",
            "                kl_s = F.pad(kl[:, :, :, :d_rev], (-d_rev, 0, 0, 0))\n",
            "                vl_s = F.pad(vl[:, :, :, :d_rev], (-d_rev, 0, 0, 0))\n",
            "            corr_r2l.append(torch.sum(qr * kl_s, dim=1, keepdim=True) * self.scale)\n",
            "            shifted_v_l.append(vl_s)\n",
            "        w_l2r = F.softmax(torch.cat(corr_l2r, dim=1), dim=1)\n",
            "        f_r2l = torch.sum(torch.stack(shifted_v_r, dim=1) * w_l2r.unsqueeze(2), dim=1)\n",
            "        w_r2l = F.softmax(torch.cat(corr_r2l, dim=1), dim=1)\n",
            "        f_l2r = torch.sum(torch.stack(shifted_v_l, dim=1) * w_r2l.unsqueeze(2), dim=1)\n",
            "        out_l = x_l + f_r2l * self.beta\n",
            "        out_r = x_r + f_l2r * self.gamma\n",
            "        if return_disp:\n",
            "            disp_vals = torch.arange(self.min_disp, self.max_disp + 1, device=x_l.device, dtype=x_l.dtype).view(1, -1, 1, 1)\n",
            "            pred_disp = torch.sum(w_l2r * disp_vals, dim=1, keepdim=True)\n",
            "            return out_l, out_r, pred_disp\n",
            "        return out_l, out_r\n",
            "\n",
            "class DyTNAFBlock(nn.Module):\n",
            "    def __init__(self, c: int, dw_expand: int = 2, ffn_expand: int = 2):\n",
            "        super().__init__()\n",
            "        dw_c = c * dw_expand\n",
            "        self.conv1 = nn.Conv2d(c, dw_c, kernel_size=1)\n",
            "        self.conv2 = nn.Conv2d(dw_c, dw_c, kernel_size=3, padding=1, groups=dw_c)\n",
            "        self.conv3 = nn.Conv2d(dw_c // 2, c, kernel_size=3, padding=1, groups=c // 4)\n",
            "        self.sg = SimpleGate()\n",
            "        ffn_c = ffn_expand * c\n",
            "        self.conv4 = nn.Conv2d(c, ffn_c, kernel_size=1)\n",
            "        self.conv5 = nn.Conv2d(ffn_c // 2, c, kernel_size=1)\n",
            "        self.norm1 = DynamicTanh(c)\n",
            "        self.norm2 = DynamicTanh(c)\n",
            "        self.beta = nn.Parameter(torch.zeros(1, c, 1, 1))\n",
            "        self.gamma = nn.Parameter(torch.zeros(1, c, 1, 1))\n",
            "    def forward(self, inp: torch.Tensor) -> torch.Tensor:\n",
            "        x = self.norm1(inp)\n",
            "        x = self.conv3(self.sg(self.conv2(self.conv1(x))))\n",
            "        y = inp + x * self.beta\n",
            "        x = self.norm2(y)\n",
            "        x = self.conv5(self.sg(self.conv4(x)))\n",
            "        return y + x * self.gamma\n",
            "\n",
            "class DyTScaleAdapter(nn.Module):\n",
            "    def __init__(self, channels: int, hidden_dim: int = 16):\n",
            "        super().__init__()\n",
            "        self.mlp = nn.Sequential(\n",
            "            nn.Linear(1, hidden_dim),\n",
            "            nn.GELU(),\n",
            "            nn.Linear(hidden_dim, channels)\n",
            "        )\n",
            "        self.norm = DynamicTanh(channels)\n",
            "    def forward(self, feat: torch.Tensor, scale: float):\n",
            "        scale_t = torch.tensor([[float(scale)]], device=feat.device, dtype=feat.dtype)\n",
            "        mod = torch.sigmoid(self.mlp(scale_t)).unsqueeze(-1).unsqueeze(-1)\n",
            "        return self.norm(feat) * mod + feat\n",
            "\n",
            "class ContinuousDyTEdgeINR(nn.Module):\n",
            "    def __init__(self, in_channels: int = 3, width: int = 48, num_blks: int = 4, min_disp: int = -2, max_disp: int = 14):\n",
            "        super().__init__()\n",
            "        self.width = width\n",
            "        self.intro = nn.Conv2d(in_channels, width, kernel_size=3, padding=1)\n",
            "        self.stereo_fusion = WindowedSCAM(width, min_disp=min_disp, max_disp=max_disp)\n",
            "        self.blocks = nn.ModuleList([DyTNAFBlock(width) for _ in range(num_blks)])\n",
            "        self.scale_adapter = DyTScaleAdapter(width)\n",
            "        self.up_4x = nn.Sequential(\n",
            "            nn.Conv2d(width, in_channels * 16, kernel_size=3, padding=1),\n",
            "            nn.PixelShuffle(4)\n",
            "        )\n",
            "        self.cont_head = nn.Sequential(\n",
            "            nn.Conv2d(width, width, kernel_size=3, padding=1),\n",
            "            DynamicTanh(width),\n",
            "            nn.Conv2d(width, in_channels, kernel_size=1)\n",
            "        )\n",
            "        nn.init.zeros_(self.up_4x[0].weight)\n",
            "        nn.init.zeros_(self.up_4x[0].bias)\n",
            "        nn.init.zeros_(self.cont_head[2].weight)\n",
            "        nn.init.zeros_(self.cont_head[2].bias)\n",
            "\n",
            "    def forward(self, img_l: torch.Tensor, img_r: torch.Tensor, scale: float = 4.0, return_disp: bool = False):\n",
            "        fl = self.intro(img_l)\n",
            "        fr = self.intro(img_r)\n",
            "        if return_disp:\n",
            "            fl, fr, pred_disp = self.stereo_fusion(fl, fr, return_disp=True)\n",
            "        else:\n",
            "            fl, fr = self.stereo_fusion(fl, fr)\n",
            "        for i, b in enumerate(self.blocks):\n",
            "            if i > 0:\n",
            "                fl, fr = self.stereo_fusion(fl, fr)\n",
            "            fl = b(fl)\n",
            "            fr = b(fr)\n",
            "        fl = self.scale_adapter(fl, scale)\n",
            "        fr = self.scale_adapter(fr, scale)\n",
            "\n",
            "        if abs(scale - 4.0) < 1e-3:\n",
            "            base_l = F.interpolate(img_l, scale_factor=4.0, mode='bicubic', align_corners=False)\n",
            "            base_r = F.interpolate(img_r, scale_factor=4.0, mode='bicubic', align_corners=False)\n",
            "            out_l = self.up_4x(fl) + base_l\n",
            "            out_r = self.up_4x(fr) + base_r\n",
            "        else:\n",
            "            B, C, H, W = img_l.shape\n",
