                    "t_start = time.time()\n",
                    "\n",
                    "for epoch in range(1, epochs + 1):\n",
                    "    model.train()\n",
                    "    total_loss = 0.0\n",
                    "    t_ep = time.time()\n",
                    "\n",
                    "    for batch in train_loader:\n",
                    "        lr_l = batch['lr_l'].to(device, non_blocking=True)\n",
                    "        lr_r = batch['lr_r'].to(device, non_blocking=True)\n",
                    "        hr_l = batch['hr_l'].to(device, non_blocking=True)\n",
                    "        hr_r = batch['hr_r'].to(device, non_blocking=True)\n",
                    "\n",
                    "        optimizer.zero_grad()\n",
                    "        with torch.amp.autocast('cuda'):\n",
                    "            out_l, out_r = model(lr_l, lr_r)\n",
                    "            # 1. Charbonnier robust loss\n",
                    "            loss_charb = torch.sqrt(torch.mean((out_l - hr_l)**2) + 1e-6) + torch.sqrt(torch.mean((out_r - hr_r)**2) + 1e-6)\n",
                    "            # 2. High-Frequency Edge Gradient Loss (sharp text strokes)\n",
                    "            grad_ol_x = torch.abs(out_l[:, :, :, 1:] - out_l[:, :, :, :-1])\n",
                    "            grad_hl_x = torch.abs(hr_l[:, :, :, 1:] - hr_l[:, :, :, :-1])\n",
                    "            grad_ol_y = torch.abs(out_l[:, :, 1:, :] - out_l[:, :, :-1, :])\n",
                    "            grad_hl_y = torch.abs(hr_l[:, :, 1:, :] - hr_l[:, :, :-1, :])\n",
                    "            loss_hf = (F.l1_loss(grad_ol_x, grad_hl_x) + F.l1_loss(grad_ol_y, grad_hl_y)) * 0.15\n",
                    "            loss = loss_charb + loss_hf\n",
                    "\n",
                    "        scaler.scale(loss).backward()\n",
                    "        scaler.unscale_(optimizer)\n",
                    "        torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)\n",
                    "        scaler.step(optimizer)\n",
                    "        scaler.update()\n",
                    "        total_loss += loss.item()\n",
                    "\n",
                    "    scheduler.step()\n",
                    "    avg_loss = total_loss / len(train_loader)\n",
                    "    dt = time.time() - t_ep\n",
